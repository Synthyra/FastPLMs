class BiohubReferenceLockError(RuntimeError):
    """The checked-in Biohub reference lock or runtime differs from its contract."""


@dataclass(frozen=True)
class TargetPolicy:
    """The one supported execution target for this reference lock."""

    hardware: str
    operating_system: str
    architecture: str
    container_platform: str
    python_implementation: str
    python_version: str
    cuda_version: str
    torch_backend: str


@dataclass(frozen=True)
class ContainerPolicy:
    """Immutable build recipe and base-image identities."""

    dockerfile_path: str
    dockerfile_sha256: str
    dockerfile_frontend: str
    cuda_image: str
    cuda_image_digest: str
    python_image: str
    python_image_digest: str
    build_python_version: str


@dataclass(frozen=True)
class LockFilePolicy:
    """One canonical input and its generated hash lock."""

    input_path: str
    input_sha256: str
    lock_path: str
    lock_sha256: str
    package_count: int


@dataclass(frozen=True)
class BioTrajPolicy:
    """Pinned BioTraj source and reproducibly built native wheel."""

    version: str
    sdist_url: str
    sdist_sha256: str
    wheel_filename: str
    wheel_sha256: str
    wheel_size: int


@dataclass(frozen=True)
class PipCheckPlatformException:
    """One exact upstream wheel-tag defect accepted by the locked runtime."""

    distribution: str
    version: str
    wheel_filename: str
    wheel_sha256: str
    filename_platform_tag: str
    wheel_metadata_platform_tag: str
    target_hardware: str
    target_operating_system: str
    target_architecture: str
    accepted_diagnostic: str
    resolution: str


@dataclass(frozen=True)
class BiohubReferenceLockContract:
    """Strict schema for the native Biohub dependency evidence boundary."""

    schema_version: int
    contract: str
    target: TargetPolicy
    container: ContainerPolicy
    runtime: LockFilePolicy
    build: LockFilePolicy
    biotraj: BioTrajPolicy
    bootstrap_inventory: Mapping[str, str]
    final_inventory_overlays: Mapping[str, str]
    pip_check_platform_exceptions: tuple[PipCheckPlatformException, ...]


@dataclass(frozen=True)
class ParsedLock:
    """Normalized inventory and hashes parsed from one requirements lock."""

    inventory: Mapping[str, str]
    hashes: Mapping[str, tuple[str, ...]]
    directives: tuple[str, ...]


def canonical_distribution_name(value: str) -> str:
    """Return the PEP 503 spelling used for inventory comparisons."""

    return re.sub(r"[-_.]+", "-", value).lower()


def normalize_distribution_version(name: str, value: str) -> str:
    """Normalize metadata spelling while retaining Torch's CUDA local version."""

    normalized = value.strip().lower().replace("_", ".").replace("-", ".")
    if canonical_distribution_name(name) != "torch":
        return normalized
    match = re.fullmatch(r"(\d+(?:\.\d+){2})(?:\+([a-z0-9.]+))?", normalized)
    if match is None:
        raise BiohubReferenceLockError(f"Invalid Torch version in inventory: {value!r}")
    local = match.group(2)
    if local in {"cu13.0", "cu130"}:
        local = "cu130"
    return match.group(1) + (f"+{local}" if local else "")


def _load_json(path: Path) -> dict[str, object]:
    try:
        raw: Any = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise BiohubReferenceLockError(f"Unable to read Biohub lock contract: {path}") from error
    if not isinstance(raw, dict) or not all(isinstance(key, str) for key in raw):
        raise BiohubReferenceLockError("Biohub lock contract must be a JSON object.")
    return {str(key): value for key, value in raw.items()}


def _exact_fields(raw: Mapping[str, object], expected: set[str], *, context: str) -> None:
    if set(raw) == expected:
        return
    raise BiohubReferenceLockError(
        f"{context} fields differ: missing={sorted(expected.difference(raw))}, "
        f"extra={sorted(set(raw).difference(expected))}."
    )


def _mapping(value: object, *, field: str) -> dict[str, object]:
    if not isinstance(value, Mapping) or not all(isinstance(key, str) for key in value):
        raise BiohubReferenceLockError(f"{field} must be a JSON object.")
    return {str(key): item for key, item in value.items()}


def _string(value: object, *, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise BiohubReferenceLockError(f"{field} must be a non-empty string.")
    return value


def _digest(value: object, *, field: str) -> str:
    digest = _string(value, field=field)
    if _DIGEST.fullmatch(digest) is None:
        raise BiohubReferenceLockError(f"{field} must be 64 lowercase hexadecimal characters.")
    return digest


def _positive_int(value: object, *, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise BiohubReferenceLockError(f"{field} must be a positive integer.")
    return value


def _portable_path(value: object, *, field: str) -> str:
    rendered = _string(value, field=field)
    path = PurePosixPath(rendered)
    if path.is_absolute() or ".." in path.parts or path.as_posix() != rendered:
        raise BiohubReferenceLockError(f"{field} must be a portable relative path.")
    return rendered


def _parse_target(value: object) -> TargetPolicy:
    raw = _mapping(value, field="target")
    fields = set(TargetPolicy.__dataclass_fields__)
    _exact_fields(raw, fields, context="target")
    target = TargetPolicy(
        **{field: _string(raw[field], field=f"target.{field}") for field in fields}
    )
    required = TargetPolicy(
        hardware="NVIDIA GH200 480GB",
        operating_system="linux",
        architecture="aarch64",
        container_platform="linux/arm64",
        python_implementation="CPython",
        python_version="3.12",
        cuda_version="13.0",
        torch_backend="cu130",
    )
    if target != required:
        raise BiohubReferenceLockError(f"Unsupported Biohub lock target: {target!r}")
    return target


def _parse_container(value: object) -> ContainerPolicy:
    raw = _mapping(value, field="container")
    fields = set(ContainerPolicy.__dataclass_fields__)
    _exact_fields(raw, fields, context="container")
    policy = ContainerPolicy(
        dockerfile_path=_portable_path(raw["dockerfile_path"], field="container.dockerfile_path"),
        dockerfile_sha256=_digest(raw["dockerfile_sha256"], field="container.dockerfile_sha256"),
        dockerfile_frontend=_string(
            raw["dockerfile_frontend"], field="container.dockerfile_frontend"
        ),
        cuda_image=_string(raw["cuda_image"], field="container.cuda_image"),
        cuda_image_digest=_digest(raw["cuda_image_digest"], field="container.cuda_image_digest"),
        python_image=_string(raw["python_image"], field="container.python_image"),
        python_image_digest=_digest(
            raw["python_image_digest"], field="container.python_image_digest"
        ),
        build_python_version=_string(
            raw["build_python_version"], field="container.build_python_version"
        ),
    )
    expected_frontend = (
        "docker/dockerfile:1.19@sha256:"
        "b6afd42430b15f2d2a4c5a02b919e98a525b785b1aaff16747d2f623364e39b6"
    )
    if policy.dockerfile_path != "docker/biohub-reference-lock.Dockerfile":
        raise BiohubReferenceLockError("Unexpected Biohub lock Dockerfile path.")
    if policy.dockerfile_frontend != expected_frontend:
        raise BiohubReferenceLockError("Unexpected Biohub lock Dockerfile frontend.")
    if not policy.cuda_image.endswith("@sha256:" + policy.cuda_image_digest):
        raise BiohubReferenceLockError("CUDA image does not use its declared ARM64 child digest.")
    if not policy.python_image.endswith("@sha256:" + policy.python_image_digest):
        raise BiohubReferenceLockError("Python image does not use its declared ARM64 child digest.")
    if policy.build_python_version != "3.12.11":
        raise BiohubReferenceLockError("Unexpected BioTraj build Python patch version.")
    return policy


def _parse_lock_policy(value: object, *, field: str) -> LockFilePolicy:
    raw = _mapping(value, field=field)
    fields = set(LockFilePolicy.__dataclass_fields__)
    _exact_fields(raw, fields, context=field)
    return LockFilePolicy(
        input_path=_portable_path(raw["input_path"], field=f"{field}.input_path"),
        input_sha256=_digest(raw["input_sha256"], field=f"{field}.input_sha256"),
        lock_path=_portable_path(raw["lock_path"], field=f"{field}.lock_path"),
        lock_sha256=_digest(raw["lock_sha256"], field=f"{field}.lock_sha256"),
        package_count=_positive_int(raw["package_count"], field=f"{field}.package_count"),
    )


def _parse_biotraj(value: object) -> BioTrajPolicy:
    raw = _mapping(value, field="biotraj")
    fields = set(BioTrajPolicy.__dataclass_fields__)
    _exact_fields(raw, fields, context="biotraj")
    policy = BioTrajPolicy(
        version=_string(raw["version"], field="biotraj.version"),
        sdist_url=_string(raw["sdist_url"], field="biotraj.sdist_url"),
        sdist_sha256=_digest(raw["sdist_sha256"], field="biotraj.sdist_sha256"),
        wheel_filename=_string(raw["wheel_filename"], field="biotraj.wheel_filename"),
        wheel_sha256=_digest(raw["wheel_sha256"], field="biotraj.wheel_sha256"),
        wheel_size=_positive_int(raw["wheel_size"], field="biotraj.wheel_size"),
    )
    expected_wheel = "biotraj-1.2.2-cp312-cp312-linux_aarch64.whl"
    if policy.version != "1.2.2" or policy.wheel_filename != expected_wheel:
        raise BiohubReferenceLockError("BioTraj version or native wheel tag differs.")
    parsed = urlsplit(policy.sdist_url)
    if parsed.scheme != "https" or parsed.hostname != "files.pythonhosted.org":
        raise BiohubReferenceLockError("BioTraj sdist must use the pinned Pythonhost URL.")
    if parsed.fragment != "sha256=" + policy.sdist_sha256:
        raise BiohubReferenceLockError("BioTraj sdist URL fragment differs from its digest.")
    return policy


def _parse_inventory(value: object, *, field: str) -> dict[str, str]:
    raw = _mapping(value, field=field)
    result: dict[str, str] = {}
    for raw_name, raw_version in raw.items():
        if _NAME.fullmatch(raw_name) is None:
            raise BiohubReferenceLockError(f"Invalid distribution name in {field}: {raw_name!r}")
        name = canonical_distribution_name(raw_name)
        if name != raw_name or name in result:
            raise BiohubReferenceLockError(f"{field} names must be unique and canonical.")
        result[name] = normalize_distribution_version(
            name, _string(raw_version, field=f"{field}.{name}")
        )
    return dict(sorted(result.items()))


