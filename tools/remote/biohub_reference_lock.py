def load_biohub_reference_lock_contract(path: Path) -> BiohubReferenceLockContract:
    """Load the checked-in strict GH200 lock contract."""

    raw = _load_json(path)
    expected = {
        "schema_version",
        "contract",
        "target",
        "container",
        "runtime",
        "build",
        "biotraj",
        "bootstrap_inventory",
        "final_inventory_overlays",
        "pip_check_platform_exceptions",
    }
    _exact_fields(raw, expected, context="contract")
    if raw["schema_version"] != _SCHEMA_VERSION:
        raise BiohubReferenceLockError("Unsupported Biohub lock contract schema version.")
    if raw["contract"] != "fastplms.biohub-reference-lock":
        raise BiohubReferenceLockError("Unexpected Biohub lock contract identifier.")
    bootstrap = _parse_inventory(raw["bootstrap_inventory"], field="bootstrap_inventory")
    final_overlays = _parse_inventory(
        raw["final_inventory_overlays"], field="final_inventory_overlays"
    )
    if bootstrap != {"pip": "26.1.1"}:
        raise BiohubReferenceLockError("Unexpected Biohub bootstrap inventory.")
    expected_final = {"esm": "3.3.0", "transformers": "4.57.6", "uv": "0.10.12"}
    if final_overlays != expected_final:
        raise BiohubReferenceLockError("Unexpected Biohub final inventory overlays.")
    contract = BiohubReferenceLockContract(
        schema_version=_SCHEMA_VERSION,
        contract="fastplms.biohub-reference-lock",
        target=_parse_target(raw["target"]),
        container=_parse_container(raw["container"]),
        runtime=_parse_lock_policy(raw["runtime"], field="runtime"),
        build=_parse_lock_policy(raw["build"], field="build"),
        biotraj=_parse_biotraj(raw["biotraj"]),
        bootstrap_inventory=bootstrap,
        final_inventory_overlays=final_overlays,
        pip_check_platform_exceptions=_parse_pip_check_platform_exceptions(
            raw["pip_check_platform_exceptions"]
        ),
    )
    if contract.runtime.package_count != 108 or contract.build.package_count != 7:
        raise BiohubReferenceLockError(
            "Biohub lock package counts must be 108 runtime and 7 build."
        )
    return contract


def _sha256(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError as error:
        raise BiohubReferenceLockError(f"Unable to hash required lock input: {path}") from error


def _contract_path(root: Path, relative: str) -> Path:
    root = root.resolve()
    path = root.joinpath(*PurePosixPath(relative).parts).resolve()
    try:
        path.relative_to(root)
    except ValueError as error:
        raise BiohubReferenceLockError(
            f"Contract path escapes repository root: {relative}"
        ) from error
    return path


def _read_lock(path: Path) -> tuple[list[str], bytes]:
    try:
        serialized = path.read_bytes()
        text = serialized.decode("utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise BiohubReferenceLockError(f"Unable to read requirements lock: {path}") from error
    if not serialized.endswith(b"\n") or b"\r" in serialized:
        raise BiohubReferenceLockError("Requirements lock must use canonical LF text ending in LF.")
    return text.splitlines(), serialized


def _logical_entries(lines: Sequence[str]) -> tuple[tuple[str, ...], tuple[str, ...]]:
    directives: list[str] = []
    entries: list[str] = []
    pending = ""
    for line in lines:
        if not line.strip():
            if pending:
                raise BiohubReferenceLockError("Blank line interrupts a lock continuation.")
            continue
        if line.startswith("#"):
            raise BiohubReferenceLockError("Unexpected comment in generated requirements body.")
        if line.startswith("--") and not pending:
            directives.append(line)
            continue
        continuation = line.rstrip().endswith("\\")
        piece = line.rstrip()[:-1].strip() if continuation else line.strip()
        pending = f"{pending} {piece}".strip()
        if not continuation:
            entries.append(pending)
            pending = ""
    if pending:
        raise BiohubReferenceLockError("Requirements lock ends during a continuation.")
    return tuple(directives), tuple(entries)


def _parse_hashed_lock(
    path: Path,
    *,
    header: tuple[str, str],
    directives: tuple[str, ...],
    biotraj_url: str | None,
    biotraj_digest: str | None,
    biotraj_version: str,
) -> ParsedLock:
    lines, _ = _read_lock(path)
    if tuple(lines[:2]) != header:
        raise BiohubReferenceLockError("Generated lock header differs from the stable command.")
    observed_directives, entries = _logical_entries(lines[2:])
    if observed_directives != directives:
        raise BiohubReferenceLockError(
            f"Generated lock directives differ: {observed_directives!r}."
        )
    inventory: dict[str, str] = {}
    hashes_by_name: dict[str, tuple[str, ...]] = {}
    observed_order: list[str] = []
    for entry in entries:
        hashes = tuple(_HASH_OPTION.findall(entry))
        requirement = _HASH_OPTION.sub("", entry).strip()
        pinned = _PINNED.fullmatch(requirement)
        if pinned is not None:
            raw_name = pinned.group("name")
            version = pinned.group("version")
        elif biotraj_url is not None and requirement == f"biotraj @ {biotraj_url}":
            raw_name = "biotraj"
            version = biotraj_version
            if hashes != (biotraj_digest,):
                raise BiohubReferenceLockError(
                    "BioTraj lock must contain only its selected digest."
                )
        else:
            raise BiohubReferenceLockError(
                f"Unpinned or unsupported lock requirement: {requirement}"
            )
        name = canonical_distribution_name(raw_name)
        if raw_name != name or name in inventory:
            raise BiohubReferenceLockError(f"Duplicate or non-canonical lock name: {raw_name!r}")
        if not hashes or tuple(sorted(set(hashes))) != hashes:
            raise BiohubReferenceLockError(f"Hashes for {name!r} must be unique and sorted.")
        inventory[name] = normalize_distribution_version(name, version)
        hashes_by_name[name] = hashes
        observed_order.append(name)
    if observed_order != sorted(observed_order):
        raise BiohubReferenceLockError("Generated lock inventory is not sorted by canonical name.")
    return ParsedLock(
        inventory=dict(sorted(inventory.items())),
        hashes=dict(sorted(hashes_by_name.items())),
        directives=observed_directives,
    )


def verify_biohub_reference_lock_contract(
    repository_root: Path,
    contract_path: Path,
) -> dict[str, object]:
    """Rehash every input and validate both generated dependency graphs."""

    contract = load_biohub_reference_lock_contract(contract_path)
    file_policies = (contract.runtime, contract.build)
    for policy in file_policies:
        for relative, expected in (
            (policy.input_path, policy.input_sha256),
            (policy.lock_path, policy.lock_sha256),
        ):
            actual = _sha256(_contract_path(repository_root, relative))
            if actual != expected:
                raise BiohubReferenceLockError(
                    f"Biohub lock file digest differs for {relative}: "
                    f"expected {expected}, received {actual}."
                )
    dockerfile = _contract_path(repository_root, contract.container.dockerfile_path)
    if _sha256(dockerfile) != contract.container.dockerfile_sha256:
        raise BiohubReferenceLockError("Biohub reference lock Dockerfile digest differs.")

    runtime_lock = _parse_hashed_lock(
        _contract_path(repository_root, contract.runtime.lock_path),
        header=_RUNTIME_HEADER,
        directives=_RUNTIME_DIRECTIVES,
        biotraj_url=contract.biotraj.sdist_url,
        biotraj_digest=contract.biotraj.sdist_sha256,
        biotraj_version=contract.biotraj.version,
    )
    build_lock = _parse_hashed_lock(
        _contract_path(repository_root, contract.build.lock_path),
        header=_BUILD_HEADER,
        directives=_BUILD_DIRECTIVES,
        biotraj_url=None,
        biotraj_digest=None,
        biotraj_version=contract.biotraj.version,
    )
    if len(runtime_lock.inventory) != contract.runtime.package_count:
        raise BiohubReferenceLockError("Runtime dependency graph package count differs.")
    if len(build_lock.inventory) != contract.build.package_count:
        raise BiohubReferenceLockError("BioTraj build graph package count differs.")
    if dict(build_lock.inventory) != _BUILD_INVENTORY:
        raise BiohubReferenceLockError("BioTraj PEP 517 build toolchain differs.")
    for name, expected in _RUNTIME_SENTINELS.items():
        if runtime_lock.inventory.get(name) != expected:
            raise BiohubReferenceLockError(
                f"Runtime lock sentinel {name!r} differs from {expected!r}."
            )
    if runtime_lock.inventory.get("biotraj") != contract.biotraj.version:
        raise BiohubReferenceLockError("Runtime BioTraj version differs from source contract.")
    for exception in contract.pip_check_platform_exceptions:
        if runtime_lock.inventory.get(exception.distribution) != exception.version:
            raise BiohubReferenceLockError(
                "Pip-check exception distribution differs from the runtime lock."
            )
        if exception.wheel_sha256 not in runtime_lock.hashes.get(exception.distribution, ()):
            raise BiohubReferenceLockError(
                "Pip-check exception wheel digest is absent from the runtime lock."
            )
    forbidden = {"esm", "pip", "transformers", "uv"}.intersection(runtime_lock.inventory)
    if forbidden:
        raise BiohubReferenceLockError(
            f"Source/bootstrap overlays leaked into runtime dependency graph: {sorted(forbidden)}"
        )
    return {
        "schema_version": _SCHEMA_VERSION,
        "target": asdict(contract.target),
        "runtime_lock_sha256": contract.runtime.lock_sha256,
        "runtime_package_count": len(runtime_lock.inventory),
        "build_lock_sha256": contract.build.lock_sha256,
        "build_package_count": len(build_lock.inventory),
        "biotraj_sdist_sha256": contract.biotraj.sdist_sha256,
        "biotraj_wheel_sha256": contract.biotraj.wheel_sha256,
        "pip_check_platform_exceptions": [
            asdict(exception) for exception in contract.pip_check_platform_exceptions
        ],
    }


def expected_installed_inventory(
    repository_root: Path,
    contract_path: Path,
    *,
    profile: str,
) -> dict[str, str]:
    """Return the exact expected distributions for one build/runtime phase."""

    contract = load_biohub_reference_lock_contract(contract_path)
    verify_biohub_reference_lock_contract(repository_root, contract_path)
    if profile == "build":
        return dict(_BUILD_INVENTORY)
    runtime_lock = _parse_hashed_lock(
        _contract_path(repository_root, contract.runtime.lock_path),
        header=_RUNTIME_HEADER,
        directives=_RUNTIME_DIRECTIVES,
        biotraj_url=contract.biotraj.sdist_url,
        biotraj_digest=contract.biotraj.sdist_sha256,
        biotraj_version=contract.biotraj.version,
    )
    expected = dict(runtime_lock.inventory)
    if profile not in {"runtime", "final"}:
        raise BiohubReferenceLockError(f"Unsupported installed-inventory profile: {profile!r}")
    for name, version in contract.bootstrap_inventory.items():
        if name in expected:
            raise BiohubReferenceLockError(f"Bootstrap inventory collides with lock: {name}")
        expected[name] = version
    if profile == "final":
        for name, version in contract.final_inventory_overlays.items():
            if name in expected:
                raise BiohubReferenceLockError(
                    f"Final inventory overlay collides with lock: {name}"
                )
            expected[name] = version
    return dict(sorted(expected.items()))


def installed_distribution_inventory() -> dict[str, str]:
    """Collect the current interpreter's exact normalized distribution inventory."""

    inventory: dict[str, str] = {}
    for distribution in importlib.metadata.distributions():
        raw_name = distribution.metadata.get("Name")
        if not isinstance(raw_name, str) or not raw_name:
            raise BiohubReferenceLockError("Installed distribution has no Name metadata.")
        name = canonical_distribution_name(raw_name)
        version = normalize_distribution_version(name, distribution.version)
        if name in inventory:
            raise BiohubReferenceLockError(f"Duplicate installed distribution metadata: {name}")
        inventory[name] = version
    return dict(sorted(inventory.items()))


def assert_exact_installed_inventory(
    expected: Mapping[str, str],
    observed: Mapping[str, str],
) -> dict[str, str]:
    """Fail closed on a missing, extra, or version-divergent distribution."""

    normalized_observed: dict[str, str] = {}
    for raw_name, raw_version in observed.items():
        name = canonical_distribution_name(raw_name)
        if name in normalized_observed:
            raise BiohubReferenceLockError(f"Observed inventory contains duplicate name: {name}")
        normalized_observed[name] = normalize_distribution_version(name, raw_version)
    normalized_expected = {
        canonical_distribution_name(name): normalize_distribution_version(name, version)
        for name, version in expected.items()
    }
    missing = sorted(set(normalized_expected).difference(normalized_observed))
    extra = sorted(set(normalized_observed).difference(normalized_expected))
    changed = {
        name: {
            "expected": normalized_expected[name],
            "observed": normalized_observed[name],
        }
        for name in sorted(set(normalized_expected).intersection(normalized_observed))
        if normalized_expected[name] != normalized_observed[name]
    }
    if missing or extra or changed:
        raise BiohubReferenceLockError(
            "Installed distribution inventory differs: "
            f"missing={missing}, extra={extra}, changed={changed}."
        )
    return dict(sorted(normalized_observed.items()))


def verify_current_installed_inventory(
    repository_root: Path,
    contract_path: Path,
    *,
    profile: str,
) -> dict[str, str]:
    """Verify the current Python environment against one exact lock profile."""

    expected = expected_installed_inventory(repository_root, contract_path, profile=profile)
    return assert_exact_installed_inventory(expected, installed_distribution_inventory())


def verify_current_pip_check(
    repository_root: Path,
    contract_path: Path,
) -> dict[str, object]:
    """Run pip check while accepting only the attested NVIDIA SBSA tag defect."""

    contract = load_biohub_reference_lock_contract(contract_path)
    verify_biohub_reference_lock_contract(repository_root, contract_path)
    verify_current_installed_inventory(repository_root, contract_path, profile="final")
    if (
        platform.system().lower() != contract.target.operating_system
        or platform.machine() != contract.target.architecture
    ):
        raise BiohubReferenceLockError(
            "Pip-check platform exception is valid only on locked Linux/aarch64."
        )
    exception = contract.pip_check_platform_exceptions[0]
    if (
        exception.target_hardware != contract.target.hardware
        or exception.target_operating_system != contract.target.operating_system
        or exception.target_architecture != contract.target.architecture
    ):
        raise BiohubReferenceLockError(
            "Pip-check platform exception target differs from the lock target."
        )
    try:
        distribution = importlib.metadata.distribution(exception.distribution)
        wheel_metadata = distribution.read_text("WHEEL")
    except (importlib.metadata.PackageNotFoundError, OSError) as error:
        raise BiohubReferenceLockError(
            "Unable to inspect the accepted pip-check exception distribution."
        ) from error
    if wheel_metadata is None:
        raise BiohubReferenceLockError(
            "Accepted pip-check exception distribution has no WHEEL metadata."
        )
    wheel_tags = tuple(
        line.removeprefix("Tag: ").strip()
        for line in wheel_metadata.splitlines()
        if line.startswith("Tag: ")
    )
    if wheel_tags != (exception.wheel_metadata_platform_tag,):
        raise BiohubReferenceLockError(
            "NVIDIA cuSPARSELt WHEEL tag differs from the accepted vendor defect."
        )
    try:
        completed = subprocess.run(
            [sys.executable, "-m", "pip", "check"],
            check=False,
            capture_output=True,
            text=True,
            timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise BiohubReferenceLockError("Unable to execute pip check.") from error
    diagnostics = tuple(
        line.strip()
        for stream in (completed.stdout, completed.stderr)
        for line in stream.splitlines()
        if line.strip()
    )
    if completed.returncode != 1 or diagnostics != (exception.accepted_diagnostic,):
        raise BiohubReferenceLockError(
            "Pip check differs from the one accepted NVIDIA wheel-tag diagnostic: "
            f"returncode={completed.returncode}, diagnostics={diagnostics!r}."
        )
    return {
        "status": "accepted-platform-exception",
        "returncode": completed.returncode,
        "diagnostics": list(diagnostics),
        "accepted_platform_exceptions": [asdict(exception)],
    }


def _atomic_write(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_bytes(payload)
    temporary.replace(path)


def materialize_biotraj_wheel_lock(
    repository_root: Path,
    contract_path: Path,
    wheel: Path,
    output: Path,
    *,
    wheel_uri: str,
) -> ParsedLock:
    """Replace the attested BioTraj sdist with its attested native wheel."""

    contract = load_biohub_reference_lock_contract(contract_path)
    verify_biohub_reference_lock_contract(repository_root, contract_path)
    if wheel.name != contract.biotraj.wheel_filename:
        raise BiohubReferenceLockError("BioTraj wheel filename differs from native target tag.")
    if wheel.stat().st_size != contract.biotraj.wheel_size:
        raise BiohubReferenceLockError("BioTraj wheel size differs from deterministic build.")
    if _sha256(wheel) != contract.biotraj.wheel_sha256:
        raise BiohubReferenceLockError("BioTraj wheel digest differs from deterministic build.")
    parsed_uri = urlsplit(wheel_uri)
    if (
        parsed_uri.scheme != "file"
        or parsed_uri.netloc
        or parsed_uri.query
        or parsed_uri.fragment
        or PurePosixPath(parsed_uri.path).name != contract.biotraj.wheel_filename
    ):
        raise BiohubReferenceLockError("Materialized BioTraj wheel URI is not an exact file URI.")

    lock_path = _contract_path(repository_root, contract.runtime.lock_path)
    lines, _ = _read_lock(lock_path)
    rendered: list[str] = []
    replaced = False
    index = 0
    while index < len(lines):
        line = lines[index]
        if line == "--no-binary biotraj":
            index += 1
            continue
        if line.startswith("biotraj @ "):
            if replaced:
                raise BiohubReferenceLockError("Runtime lock contains duplicate BioTraj entries.")
            while line.rstrip().endswith("\\"):
                index += 1
                if index >= len(lines):
                    raise BiohubReferenceLockError("BioTraj lock entry ends during continuation.")
                line = lines[index]
            rendered.extend(
                (
                    f"biotraj @ {wheel_uri} \\",
                    f"    --hash=sha256:{contract.biotraj.wheel_sha256}",
                )
            )
            replaced = True
            index += 1
            continue
        rendered.append(line)
        index += 1
    if not replaced:
        raise BiohubReferenceLockError("Runtime lock contains no BioTraj source entry.")
    _atomic_write(output, ("\n".join(rendered) + "\n").encode())
    materialized = _parse_hashed_lock(
        output,
        header=_RUNTIME_HEADER,
        directives=_MATERIALIZED_DIRECTIVES,
        biotraj_url=wheel_uri,
        biotraj_digest=contract.biotraj.wheel_sha256,
        biotraj_version=contract.biotraj.version,
    )
    if len(materialized.inventory) != contract.runtime.package_count:
        raise BiohubReferenceLockError("Materialized runtime lock package count differs.")
    return materialized


def _first_command_line(command: Sequence[str]) -> str:
    try:
        completed = subprocess.run(
            command,
            check=True,
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
        raise BiohubReferenceLockError(
            f"Unable to attest toolchain command: {command!r}"
        ) from error
    lines = completed.stdout.splitlines()
    if not lines:
        raise BiohubReferenceLockError(f"Toolchain command emitted no version: {command!r}")
    return lines[0]


def _gpu_name() -> str:
    try:
        completed = subprocess.run(
            ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
            check=True,
            capture_output=True,
            text=True,
            timeout=15,
        )
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
        raise BiohubReferenceLockError("Unable to attest the GH200 build host.") from error
    names = tuple(line.strip() for line in completed.stdout.splitlines() if line.strip())
    if len(names) != 1:
        raise BiohubReferenceLockError(f"Expected one GH200 device, received {names!r}.")
    return names[0]


def write_biohub_reference_build_evidence(
    repository_root: Path,
    contract_path: Path,
    wheel: Path,
    output: Path,
    *,
    build_image_id: str,
) -> dict[str, object]:
    """Write native image, toolchain, wheel, and build-inventory evidence."""

    contract = load_biohub_reference_lock_contract(contract_path)
    lock_evidence = verify_biohub_reference_lock_contract(repository_root, contract_path)
    if _IMAGE_ID.fullmatch(build_image_id) is None:
        raise BiohubReferenceLockError("Build image identity must be a sha256 Docker image ID.")
    if platform.system().lower() != contract.target.operating_system:
        raise BiohubReferenceLockError("Build operating system differs from lock target.")
    if platform.machine() != contract.target.architecture:
        raise BiohubReferenceLockError("Build architecture differs from lock target.")
    if platform.python_implementation() != contract.target.python_implementation:
        raise BiohubReferenceLockError("Build Python implementation differs from lock target.")
    python_version = platform.python_version()
    if python_version != contract.container.build_python_version:
        raise BiohubReferenceLockError("Build Python patch version differs from pinned image.")
    hardware = _gpu_name()
    if hardware != contract.target.hardware:
        raise BiohubReferenceLockError(
            f"Build hardware differs: expected {contract.target.hardware!r}, received {hardware!r}."
        )
    if wheel.name != contract.biotraj.wheel_filename:
        raise BiohubReferenceLockError("Evidence wheel filename differs from contract.")
    if wheel.stat().st_size != contract.biotraj.wheel_size:
        raise BiohubReferenceLockError("Evidence wheel size differs from contract.")
    if _sha256(wheel) != contract.biotraj.wheel_sha256:
        raise BiohubReferenceLockError("Evidence wheel digest differs from contract.")
    inventory = verify_current_installed_inventory(repository_root, contract_path, profile="build")
    payload: dict[str, object] = {
        "schema_version": _EVIDENCE_SCHEMA_VERSION,
        "contract_sha256": _sha256(contract_path),
        "target": asdict(contract.target),
        "container": {
            **asdict(contract.container),
            "build_image_id": build_image_id,
        },
        "observed": {
            "hardware": hardware,
            "operating_system": platform.system().lower(),
            "architecture": platform.machine(),
            "python_implementation": platform.python_implementation(),
            "python_version": python_version,
            "gcc": _first_command_line(("gcc", "--version")),
            "binutils": _first_command_line(("ld", "--version")),
        },
        "locks": lock_evidence,
        "biotraj": {
            **asdict(contract.biotraj),
            "observed_wheel_sha256": _sha256(wheel),
            "observed_wheel_size": wheel.stat().st_size,
        },
        "installed_build_inventory": inventory,
    }
    _atomic_write(output, (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode())
    return payload


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    verify = subparsers.add_parser("verify-contract")
    verify.add_argument("--root", type=Path, required=True)
    verify.add_argument("--contract", type=Path, required=True)
    inventory = subparsers.add_parser("verify-inventory")
    inventory.add_argument("--root", type=Path, required=True)
    inventory.add_argument("--contract", type=Path, required=True)
    inventory.add_argument("--profile", choices=("build", "runtime", "final"), required=True)
    pip_check = subparsers.add_parser("verify-pip-check")
    pip_check.add_argument("--root", type=Path, required=True)
    pip_check.add_argument("--contract", type=Path, required=True)
    materialize = subparsers.add_parser("materialize-wheel-lock")
    materialize.add_argument("--root", type=Path, required=True)
    materialize.add_argument("--contract", type=Path, required=True)
    materialize.add_argument("--wheel", type=Path, required=True)
    materialize.add_argument("--wheel-uri", required=True)
    materialize.add_argument("--output", type=Path, required=True)
    evidence = subparsers.add_parser("write-build-evidence")
    evidence.add_argument("--root", type=Path, required=True)
    evidence.add_argument("--contract", type=Path, required=True)
    evidence.add_argument("--wheel", type=Path, required=True)
    evidence.add_argument(
        "--build-image-id",
        default=os.environ.get("FASTPLMS_BUILD_IMAGE_ID"),
        required="FASTPLMS_BUILD_IMAGE_ID" not in os.environ,
    )
    evidence.add_argument("--output", type=Path, required=True)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Validate the lock, materialize its wheel, or write native build evidence."""

    arguments = _parser().parse_args(argv)
    if arguments.command == "verify-contract":
        result: object = verify_biohub_reference_lock_contract(arguments.root, arguments.contract)
    elif arguments.command == "verify-inventory":
        result = verify_current_installed_inventory(
            arguments.root, arguments.contract, profile=arguments.profile
        )
    elif arguments.command == "verify-pip-check":
        result = verify_current_pip_check(arguments.root, arguments.contract)
    elif arguments.command == "materialize-wheel-lock":
        parsed = materialize_biotraj_wheel_lock(
            arguments.root,
            arguments.contract,
            arguments.wheel,
            arguments.output,
            wheel_uri=arguments.wheel_uri,
        )
        result = {"package_count": len(parsed.inventory), "output": str(arguments.output)}
    else:
        result = write_biohub_reference_build_evidence(
            arguments.root,
            arguments.contract,
            arguments.wheel,
            arguments.output,
            build_image_id=arguments.build_image_id,
        )
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
